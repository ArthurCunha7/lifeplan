export function HabitsIcon({
  name,
  className = 'ico',
}: {
  name: HabitsIconName;
  className?: string;
}) {
  return (
    <span className={className} aria-hidden="true">
      <svg viewBox="0 0 24 24">{ICON_PATHS[name]}</svg>
    </span>
  );
}

export function RichText({ parts }: { parts: RichTextPart[] }) {
  return (
    <>
      {parts.map((part, idx) => {
        if (typeof part === 'string') {
          return <Fragment key={idx}>{part}</Fragment>;
        }
        if ('bold' in part) {
          return <strong key={idx}>{part.bold}</strong>;
        }
        return (
          <span key={idx} className="stat-num">
            {part.stat}
          </span>
        );
      })}
    </>
  );
}
