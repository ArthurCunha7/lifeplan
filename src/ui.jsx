export function Icon({name,size=22,stroke=1.75,style,title}){
  const body=PATHS[name];
  if(!body) return null;
  return(
    <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={stroke}
      strokeLinecap="round" strokeLinejoin="round"
      aria-hidden={title?undefined:'true'} role={title?'img':undefined} aria-label={title}
      style={{flexShrink:0,...style}}>{body}</svg>
  );
}

// Mostra um ícone de linha quando `name` existe; senão mostra o texto (ex.: emoji salvo antes pelo usuário)
export function Glyph({name,size=20,style}){
  if(PATHS[name]) return <Icon name={name} size={size} style={style}/>;
  return name?<span style={{fontSize:size,lineHeight:1,...style}}>{name}</span>:null;
}

